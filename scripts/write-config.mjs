#!/usr/bin/env node
// Generates tgcloud/lib/config.js from OWNER_IDS (environment first, then .env).
// The platform has no environment variables or secrets, so per-deployment values
// are baked into this git-ignored module at deploy time. Keeps owner ids out of git.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** @param {string | undefined} raw @returns {number[]} */
export function parseOwnerIds(raw) {
  const parts = String(raw ?? '')
    .split(/[\s,]+/)
    .filter(Boolean);
  if (parts.length === 0) {
    throw new Error('OWNER_IDS is empty. Set it to the Telegram user ids of the bot owners.');
  }
  const ids = parts.map((p) => {
    if (!/^\d+$/.test(p) || Number(p) <= 0 || !Number.isSafeInteger(Number(p))) {
      throw new Error(`OWNER_IDS: not a valid Telegram user id: "${p}"`);
    }
    return Number(p);
  });
  return [...new Set(ids)];
}

/** @param {string} file @returns {Record<string, string>} */
export function readEnvFile(file) {
  if (!existsSync(file)) return {};
  /** @type {Record<string, string>} */
  const out = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

/** @param {number[]} ids */
export function renderConfig(ids) {
  return (
    '// Generated by scripts/write-config.mjs from OWNER_IDS. Do not edit or commit.\n' +
    `export const OWNER_IDS = [${ids.join(', ')}];\n`
  );
}

export function writeConfig({
  env = process.env,
  envFile = join(ROOT, '.env'),
  outFile = join(ROOT, 'tgcloud/lib/config.js'),
} = {}) {
  const raw = env.OWNER_IDS || readEnvFile(envFile).OWNER_IDS;
  const ids = parseOwnerIds(raw);
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, renderConfig(ids));
  return ids;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    const ids = writeConfig();
    console.log(`Wrote tgcloud/lib/config.js with ${ids.length} owner id(s).`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
